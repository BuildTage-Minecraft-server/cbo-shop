export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, scale = 2, className }: { name: IconName; scale?: number; className?: string }) {
  const rows: readonly string[] = ICONS[name];
  const columns = rows[0].length;
  const path = rows
    .flatMap((row, y) => Array.from(row, (cell, x) => (cell === "#" ? `M${x} ${y}h1v1h-1z` : "")))
    .join("");

  return (
    <svg
      viewBox={`0 0 ${columns} ${rows.length}`}
      width={columns * scale}
      height={rows.length * scale}
      aria-hidden="true"
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
    >
      <path d={path} />
    </svg>
  );
}
